import { execFile } from 'node:child_process';
import { readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);
const root = process.cwd();
const imageDir = path.join(root, 'public', 'images');
const outFile = path.join(root, 'src', 'lib', 'productPalette.ts');
const converter = process.env.IMAGEMAGICK_BIN || 'convert';

const DEPARTMENT_DIRS = ['clothing', 'pants', 'glasses', 'watch', 'bag', 'accessory'];

async function readPixel(args) {
  const { stdout } = await execFileAsync(converter, args);
  const value = stdout.trim();
  const percent = value.match(/srgb\(([\d.]+)%,([\d.]+)%,([\d.]+)%\)/);
  if (percent) {
    return [1, 2, 3].map((index) => Math.round((Number(percent[index]) / 100) * 255));
  }
  const abs =
    value.match(/rgba?\((\d+),(\d+),(\d+)/) || value.match(/srgb\((\d+),(\d+),(\d+)\)/);
  if (abs) return [Number(abs[1]), Number(abs[2]), Number(abs[3])];
  throw new Error(`could not read colour: ${value}`);
}

const distance = (a, b) =>
  Math.sqrt((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2);

/**
 * Product photos are lifestyle shots on warm studio walls, so a plain average
 * is just "beige". Instead: quantise the garment area into two clusters, throw
 * away the one that matches the wall, and keep the largest remaining cluster.
 */
async function garmentTone(file) {
  const background = await readPixel([
    file,
    '-auto-orient',
    '-format',
    '%[pixel:p{4,4}]',
    'info:',
  ]);

  const { stdout } = await execFileAsync(converter, [
    file,
    '-auto-orient',
    '-resize',
    '64x64^',
    '-gravity',
    'center',
    '-crop',
    '46%x54%+0+8%',
    '+repage',
    '-colors',
    '3',
    '-format',
    '%c',
    'histogram:info:-',
  ]);

  const clusters = stdout
    .split('\n')
    .map((line) => {
      const match = line.match(/^\s*(\d+):.*?(#[0-9A-Fa-f]{6})/);
      if (!match) return null;
      const hex = match[2].slice(1);
      const rgb = [0, 2, 4].map((offset) => parseInt(hex.slice(offset, offset + 2), 16));
      return { count: Number(match[1]), rgb };
    })
    .filter(Boolean);

  if (!clusters.length) throw new Error(`no colour clusters in ${file}`);

  const garment = clusters
    .filter((cluster) => distance(cluster.rgb, background) > 46)
    .sort((a, b) => b.count - a.count)[0];

  return (garment ?? clusters.sort((a, b) => b.count - a.count)[0]).rgb;
}

const toHex = ([r, g, b]) =>
  `#${[r, g, b].map((value) => value.toString(16).padStart(2, '0')).join('')}`;

/* Perceived brightness (ITU-R BT.601). */
const luminance = ([r, g, b]) => Math.round((0.299 * r + 0.587 * g + 0.114 * b) / 2.55);

async function main() {
  const entries = [];
  for (const dir of DEPARTMENT_DIRS) {
    const dirPath = path.join(imageDir, dir);
    let files = [];
    try {
      files = await readdir(dirPath);
    } catch {
      continue;
    }
    for (const name of files.filter((file) => file.endsWith('.jpg')).sort()) {
      const file = path.join(dirPath, name);
      await stat(file);
      const rgb = await garmentTone(file);
      const hex = toHex(rgb);
      entries.push({
        key: `/images/${dir}/${name}`,
        hex,
        // 0 = black, 100 = white: used to alternate light and dark pieces
        l: luminance(rgb),
      });
    }
  }

  const body = entries
    .map((entry) => `  '${entry.key}': { hex: '${entry.hex}', l: ${entry.l} },`)
    .join('\n');

  const content = `// AUTO-GENERATED by scripts/generate-product-palette.mjs — do not edit by hand.
// Average colour of every catalogue photo, used to style and order the rack.

export type ProductTone = {
  /** Average colour of the product photo. */
  hex: string;
  /** Perceived brightness, 0 (black) … 100 (white). */
  l: number;
};

export const productPalette: Record<string, ProductTone> = {
${body}
};

/** Falls back to a warm neutral when a product has no local photo. */
export function toneFor(image: string | null | undefined): ProductTone {
  if (!image) return { hex: '#d8cfbf', l: 80 };
  return productPalette[image] ?? { hex: '#d8cfbf', l: 80 };
}
`;

  await writeFile(outFile, content, 'utf8');
  console.log(`wrote ${entries.length} tones to ${path.relative(root, outFile)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
